"""
Admin CMS API (PRD sections 28/29, decision D-02, contract section 8).

Every route in this module is gated by `require_admin` at the router level, so
a new endpoint added here is authenticated and role-checked by construction
rather than by the author remembering to add a dependency.

Content CRUD for the four editable types is generated by
`register_content_crud` rather than written out four times. That is not just
brevity: it guarantees that Event, Announcement, Temple and Ghat all get the
same guarded status transition, the same soft-delete semantics and the same
audit trail, so none of them can quietly drift into a free-form status write.
"""
