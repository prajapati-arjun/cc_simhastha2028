# --------------------------------------------------------------------------
# Verification queues
#
# This is the legitimate-purpose side of decision D-01: an authenticated
# reviewer CAN see full case detail, because verifying a missing-person report
# is impossible otherwise. The public API cannot. Every read here is a
# deliberate, authenticated, audited act.
# --------------------------------------------------------------------------
@router.get(
    "/lost-found",
    response_model=ListEnvelope[LostFoundAdminOut],
    summary="Lost & Found verification queue (full case detail)",
)
def list_lost_found_queue(
    db: DbSession,
    case_status: str | None = Query(default=None, alias="status"),
    limit: int = LimitQuery,
    offset: int = OffsetQuery,
) -> Any:
    stmt = select(LostFoundCase)
    if case_status is not None:
        stmt = stmt.where(LostFoundCase.status == case_status)
    total = count_of(db, stmt)
    rows = (
        db.execute(
            stmt.order_by(LostFoundCase.created_at.desc()).limit(limit).offset(offset)
        )
        .scalars()
        .all()
    )
    return ListEnvelope[LostFoundAdminOut].model_validate(
        build_envelope(rows, [LostFoundAdminOut.model_validate(r) for r in rows], total)
    )


@router.patch(
    "/lost-found/{item_id}",
    response_model=LostFoundAdminOut,
    summary="Move a Lost & Found case through the verification workflow",
    description=(
        "Status transition and reviewer notes only - an admin cannot rewrite "
        "what the reporter submitted. Invalid transitions are rejected with 409."
    ),
    responses={409: {"description": "Invalid status transition."}},
)
def update_lost_found_case(
    item_id: int, payload: CaseStatusUpdate, db: DbSession, admin: AdminUser
) -> Any:
    case = db.execute(
        select(LostFoundCase).where(LostFoundCase.id == item_id)
    ).scalar_one_or_none()
    if case is None:
        raise HTTPException(status_code=404, detail="Case not found")

    previous = case.status
    case.status = apply_transition(
        LOST_FOUND_TRANSITIONS, "lost_found_case", previous, payload.status
    )
    if payload.admin_notes is not None:
        case.admin_notes = payload.admin_notes
    db.flush()
    record_audit(
        db,
        action="lost_found.status_changed",
        entity_type="lost_found_case",
        entity_id=case.id,
        actor_user_id=admin.id,
        detail={
            "case_reference": case.case_reference,
            "status_from": previous,
            "status_to": case.status,
        },
    )
    db.commit()
    db.refresh(case)
    return LostFoundAdminOut.model_validate(case)


