def _orm_payload(payload: Any) -> dict[str, Any]:
    """
    Flatten a validated schema into ORM-assignable values.

    `model_dump()` preserves Enum members, and assigning one to a VARCHAR
    column persists the repr ("EventCategory.SNAN_PARVA") rather than the
    contract value ("snan_parva"). Unwrap them once, here.
    """
    return {
        key: (value.value if isinstance(value, Enum) else value)
        for key, value in payload.model_dump().items()
    }


def _get_or_404(db: Session, model: type, item_id: int) -> Any:
    row = db.execute(
        live_rows(model).where(model.id == item_id)
    ).scalar_one_or_none()
    if row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"{model.__name__} not found",
        )
    return row


def _commit_or_conflict(db: Session, entity_type: str) -> None:
    """Translate a unique-slug collision into 409 instead of a 500."""
    try:
        db.commit()
    except IntegrityError as exc:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                f"Could not save {entity_type}: a record with that slug already "
                "exists."
            ),
        ) from exc


def register_content_crud(
    *,
    path: str,
    model: type,
    entity_type: str,
    out_schema: type,
    create_schema: type,
    update_schema: type,
) -> None:
    """Attach list/create/patch/delete routes for one CMS content type."""

    @router.get(
        path,
        response_model=ListEnvelope[out_schema],
        name=f"admin_list_{entity_type}",
        operation_id=f"admin_list_{entity_type}",
        summary=f"List {entity_type} records including drafts",
    )
    def _list(
        db: DbSession,
        status_filter: ContentStatus | None = Query(
            default=None, alias="status", description="Filter by publication status."
        ),
        limit: int = LimitQuery,
        offset: int = OffsetQuery,
    ) -> Any:
        stmt = live_rows(model)
        if status_filter is not None:
            stmt = stmt.where(model.status == status_filter.value)
        total = count_of(db, stmt)
        rows = (
            db.execute(stmt.order_by(model.id.asc()).limit(limit).offset(offset))
            .scalars()
            .all()
        )
        return ListEnvelope[out_schema].model_validate(
            build_envelope(rows, [out_schema.model_validate(r) for r in rows], total)
        )

    @router.post(
        path,
        response_model=out_schema,
        status_code=status.HTTP_201_CREATED,
        name=f"admin_create_{entity_type}",
        operation_id=f"admin_create_{entity_type}",
        summary=f"Create a {entity_type} record (always starts as a draft)",
        description=(
            "New records are created with `status = \"draft\"`. Publication is a "
            "separate, explicitly guarded transition via PATCH - nothing "
            "reaches the public API on creation."
        ),
    )
    def _create(payload: create_schema, db: DbSession, admin: AdminUser) -> Any:
        row = model(
            **_orm_payload(payload),
            # Not client-controlled: an editor cannot create pre-published
            # content, and cannot claim their hand-typed row is authority-sourced.
            status=ContentStatus.DRAFT.value,
            data_source=DataSource.CMS.value,
        )
        db.add(row)
        db.flush()
        record_audit(
            db,
            action=f"{entity_type}.created",
            entity_type=entity_type,
            entity_id=row.id,
            actor_user_id=admin.id,
            detail={"slug": getattr(row, "slug", None), "status": row.status},
        )
        _commit_or_conflict(db, entity_type)
        db.refresh(row)
        return out_schema.model_validate(row)

    @router.patch(
        path + "/{item_id}",
        response_model=out_schema,
        name=f"admin_update_{entity_type}",
        operation_id=f"admin_update_{entity_type}",
        summary=f"Partially update a {entity_type} record",
        description=(
            "Supports the draft/published/archived transition. Allowed moves: "
            "draft->published, published->draft, published->archived, "
            "draft->archived. Any other move is rejected with **409**; status "
            "is never written as a free-form value."
        ),
        responses={
            404: {"description": "No such record."},
            409: {"description": "Invalid status transition, or duplicate slug."},
        },
    )
    def _update(
        item_id: int, payload: update_schema, db: DbSession, admin: AdminUser
    ) -> Any:
        row = _get_or_404(db, model, item_id)
        data = {
            key: (value.value if isinstance(value, Enum) else value)
            for key, value in payload.model_dump(exclude_unset=True).items()
        }

        requested_status = data.pop("status", None)
        transitioned_to: str | None = None
        if requested_status is not None:
            new_status = apply_transition(
                CONTENT_TRANSITIONS,
                entity_type,
                row.status,
                ContentStatus(requested_status).value,
            )
            if new_status != row.status:
                transitioned_to = new_status
                row.status = new_status
                # First publication stamps published_at so the public feed can
                # order by it; re-publishing later keeps the original stamp.
                if (
                    new_status == ContentStatus.PUBLISHED.value
                    and hasattr(row, "published_at")
                    and row.published_at is None
                ):
                    row.published_at = datetime.now(timezone.utc)

        if "verified" in data and admin.role_name != RoleName.SUPER_ADMIN.value:
            # `verified` asserts that a named authority signed the record off.
            # A content manager must not be able to grant that badge.
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Only a super_admin may change the `verified` flag.",
            )

        changed = apply_updates(row, data)
        if changed or transitioned_to:
            row.data_source = DataSource.CMS.value

        db.flush()
        record_audit(
            db,
            action=(
                f"{entity_type}.status_changed"
                if transitioned_to
                else f"{entity_type}.updated"
            ),
            entity_type=entity_type,
            entity_id=row.id,
            actor_user_id=admin.id,
            detail={
                "changed_fields": sorted(changed),
                "status_from": None if not transitioned_to else requested_status,
                "status_to": transitioned_to,
                "status": row.status,
            },
        )
        _commit_or_conflict(db, entity_type)
        db.refresh(row)
        return out_schema.model_validate(row)

    @router.delete(
        path + "/{item_id}",
        status_code=status.HTTP_204_NO_CONTENT,
        name=f"admin_delete_{entity_type}",
        operation_id=f"admin_delete_{entity_type}",
        summary=f"Retire a {entity_type} record",
        description=(
            "Soft delete. The row is marked deleted and disappears from every "
            "public and admin read, but is retained so the audit trail still "
            "resolves the record it refers to."
        ),
        responses={404: {"description": "No such record."}},
    )
    def _delete(item_id: int, db: DbSession, admin: AdminUser) -> Response:
        row = _get_or_404(db, model, item_id)
        row.deleted_at = datetime.now(timezone.utc)
        db.flush()
        record_audit(
            db,
            action=f"{entity_type}.deleted",
            entity_type=entity_type,
            entity_id=row.id,
            actor_user_id=admin.id,
            detail={"slug": getattr(row, "slug", None), "soft_delete": True},
        )
        db.commit()
        return Response(status_code=status.HTTP_204_NO_CONTENT)


