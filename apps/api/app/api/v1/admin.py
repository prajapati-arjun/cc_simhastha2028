def _counts_by_status(db: Session, model: type, soft_deleted: bool = True) -> dict[str, int]:
    stmt = select(model.status, func.count()).group_by(model.status)
    if soft_deleted and hasattr(model, "deleted_at"):
        stmt = stmt.where(model.deleted_at.is_(None))
    return {row[0]: int(row[1]) for row in db.execute(stmt).all()}


@router.get(
    "/dashboard",
    summary="Admin dashboard counts by entity and status",
    description=(
        "Aggregate counts only - no personal data. The SOS block reports the "
        "count of SIMULATED incident records held in this prototype's own "
        "database; it is not a count of real dispatches, because there are none."
    ),
)
def dashboard(db: DbSession) -> dict[str, Any]:
    content = {
        "events": _counts_by_status(db, Event),
        "announcements": _counts_by_status(db, Announcement),
        "temples": _counts_by_status(db, Temple),
        "ghats": _counts_by_status(db, Ghat),
    }
    cases = {
        "lost_found": _counts_by_status(db, LostFoundCase, soft_deleted=False),
        "missing_person": _counts_by_status(db, MissingPersonCase, soft_deleted=False),
    }
    sos_total = int(
        db.execute(select(func.count()).select_from(SosIncident)).scalar_one()
    )
    users_total = int(
        db.execute(
            select(func.count()).select_from(User).where(User.deleted_at.is_(None))
        ).scalar_one()
    )

    def _totalled(block: dict[str, dict[str, int]]) -> dict[str, dict[str, Any]]:
        return {
            key: {"total": sum(counts.values()), "by_status": counts}
            for key, counts in block.items()
        }

    return {
        "generated_at": datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z"),
        "content": _totalled(content),
        "cases": _totalled(cases),
        "sos": {"total": sos_total, "simulated": sos_total},
        "users": {"total": users_total},
        "prototype_notice": (
            "Counts reflect this prototype's own test database only. No figure "
            "here represents a real incident, dispatch or authority-verified record."
        ),
    }
